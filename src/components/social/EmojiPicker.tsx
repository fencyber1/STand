interface Props {
  onSelect: (emoji: string) => void;
  onClose: () => void;
}

export default function EmojiPicker({ onSelect, onClose }: Props) {
  const [activeCategory, setActiveCategory] = useState(0);
  const [search, setSearch] = useState('');
  const categoryNames = useMemo(() => Object.keys(EMOJI_DATA), []);

  const filteredEmojis = useMemo(() => {
    const emojis = EMOJI_DATA[categoryNames[activeCategory]] || [];
    if (!search) return emojis;
    return Object.values(EMOJI_DATA).flat().filter((e) => e.includes(search));
  }, [activeCategory, search, categoryNames]);

  return (
    <div className="bg-gray-900 rounded-2xl border border-white/10 shadow-2xl w-full max-w-sm overflow-hidden" onClick={(e) => e.stopPropagation()}>
      {/* Search */}
      <div className="p-2 border-b border-white/10">
        <input
          type="text"
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          placeholder="Search emoji..."
          className="w-full bg-white/10 rounded-lg px-3 py-2 text-sm text-white placeholder-white/30 outline-none"
        />
      </div>

      {/* Category tabs */}
      <div className="flex border-b border-white/10 overflow-x-auto">
        {categoryNames.map((name, i) => (
          <button
            key={name}
            onClick={() => { setActiveCategory(i); setSearch(''); }}
            className={`px-3 py-2 text-xs font-medium whitespace-nowrap transition-colors ${i === activeCategory && !search ? 'text-blue-400 border-b-2 border-blue-400' : 'text-white/40 hover:text-white/60'}`}
          >
            {name}
          </button>
        ))}
      </div>

      {/* Emoji grid */}
      <div className="p-2 h-64 overflow-y-auto">
        <div className="grid grid-cols-8 gap-0.5">
          {filteredEmojis.map((emoji, i) => (
            <button
              key={`${emoji}-${i}`}
              onClick={() => onSelect(emoji)}
              className="w-9 h-9 flex items-center justify-center text-xl rounded-lg hover:bg-white/10 transition-colors"
            >
              {emoji}
            </button>
          ))}
        </div>
        {filteredEmojis.length === 0 && (
          <p className="text-center text-white/30 text-sm py-8">No emojis found</p>
        )}
      </div>
    </div>
  );
}
